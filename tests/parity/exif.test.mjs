import test from "node:test"
import { root, upstreamFunctions } from "./oracle.mjs"
import { corpus, generatedCorpus, fullDirectories, jpeg, tiff } from "../../crates/freeshow-exif/tools/fixtures.mjs"

const require = createRequire(import.meta.url)
const { ExifImage } = require("exif")
assert.equal(require("exif/package.json").version, "0.6.0")
const binary = process.env.FREESHOW_EXIF_PARITY || path.join(root, "target/debug/freeshow-exif-parity" + (process.platform === "win32" ? ".exe" : ""))
const source = upstreamFunctions("src/electron/utils/files.ts", ["readExifData"], { ExifImage, actionComplete: () => {} })
import { wire } from "../../crates/freeshow-exif/tools/wire.mjs"
function native(ids, cwd = root) {
    const run = spawnSync(binary, [], { cwd, input: ids.map((id) => JSON.stringify({ id })).join("\n") + "\n", encoding: "utf8", timeout: 20000, maxBuffer: 16 * 1024 * 1024 })
    assert.equal(run.status, 0, run.stderr || run.error?.message)
    return run.stdout.trim().split("\n").map(JSON.parse)
}
async function compare(ids, cwd) {
    const results = native(ids, cwd)
    for (const [index, id] of ids.entries()) {
        const expected = wire(await source.readExifData({ id }))
        assert.equal(results[index].sourceCompatible, true, id + ": " + JSON.stringify(results[index]))
        assert.deepEqual({ reply: results[index].reply, hydration: results[index].hydration }, expected, id)
    }
    return results
}

test("actual source handler and exif 0.6.0 agree on generated byte orders/formats, groups, quirks and corrupt JPEGs", async () => {
    const folder = fs.mkdtempSync(path.join(os.tmpdir(), "freeshow-exif-parity-"))
    try {
        const fixtures = corpus()
        const ids = [...fixtures].map(([name, data]) => {
            const file = path.join(folder, name)
            fs.writeFileSync(file, data)
            return file
        })
        const values = await compare(ids)
        const full = values[0]
        assert.deepEqual(Object.keys(full.reply.exif), ["image", "thumbnail", "exif", "gps", "interoperability", "makernote"])
        assert.equal(full.reply.exif.image.Make, "Écamera\0")
        assert.equal(full.reply.exif.exif.DateTimeOriginal, "2001:02:03 04:05:06")
        assert.deepEqual(full.reply.exif.interoperability, { InteropIndex: "R98" })
        assert.equal(full.reply.exif.thumbnail.ThumbnailOffset, 2048)
        assert.ok(full.hydration.specialNumbers.some((value) => value.kind === "NegativeZero"))
        assert.ok(full.hydration.byteBuffers.includes("/exif/exif/ExifVersion"))
        for (const name of ["full-II.jpg", "full-MM.jpg", "raw-II.tiff"]) assert.deepEqual(fs.readFileSync(path.join(root, "crates/freeshow-exif/fixtures", name)), fixtures.get(name), "committed fixture drift")
    } finally {
        fs.rmSync(folder, { recursive: true, force: true })
    }
})

