test("source missing, directory, raw TIFF, malformed and literal file-URL paths retain own undefined exif", async () => {
    const folder = fs.mkdtempSync(path.join(os.tmpdir(), "freeshow-exif-日本語 é-"))
    try {
        const file = path.join(folder, "#% image.jpg")
        fs.writeFileSync(file, jpeg(tiff(fullDirectories())))
        const ids = [file, path.join(folder, "missing.jpg"), folder, pathToFileURL(file).href, path.join(root, "crates/freeshow-exif/fixtures/raw-II.tiff")]
        const values = await compare(ids)
        for (let i = 1; i < values.length; i++) {
            const original = await source.readExifData({ id: ids[i] })
            assert.equal(Object.hasOwn(original, "exif"), true)
            assert.equal(original.exif, undefined)
            assert.equal(Object.hasOwn(values[i].reply, "exif"), false)
            assert.deepEqual(values[i].hydration.undefinedPaths, ["/exif"])
        }
        const [relative] = native([path.relative(root, file)])
        assert.deepEqual(relative.reply, wire(await source.readExifData({ id: path.relative(root, file) })).reply)
    } finally {
        fs.rmSync(folder, { recursive: true, force: true })
    }
})

test("malformed non-numeric pointers are an explicit uncertified variant; empty paths fail rather than hang", () => {
    const folder = fs.mkdtempSync(path.join(os.tmpdir(), "freeshow-exif-pointer-"))
    try {
        const file = path.join(folder, "pointer.jpg")
        fs.writeFileSync(file, jpeg(tiff({ image: [{ tag: 0x8769, format: 2, data: Buffer.from("oops\0") }] })))
        const [unsupported, empty, nul] = native([file, "", "bad\0path"])
        assert.equal(unsupported.sourceCompatible, false)
        assert.equal(unsupported.diagnostics[0].code, "exif_unsupported")
        assert.equal(empty.error.code, "exif_invalid")
        assert.equal(nul.error.code, "exif_invalid")
    } finally {
        fs.rmSync(folder, { recursive: true, force: true })
    }
})

