test("actual source permission failures retain undefined; its empty-id callback never completes", async () => {
    const pending = await Promise.race([source.readExifData({ id: "" }).then(() => "completed"), new Promise((resolve) => setTimeout(() => resolve("pending"), 20))])
    assert.equal(pending, "pending")
    if (process.platform === "win32") return
    const folder = fs.mkdtempSync(path.join(os.tmpdir(), "freeshow-exif-permission-"))
    const file = path.join(folder, "denied.jpg")
    try {
        fs.writeFileSync(file, jpeg(tiff(fullDirectories())))
        fs.chmodSync(file, 0o0)
        await compare([file])
    } finally {
        fs.chmodSync(file, 0o600)
        fs.rmSync(folder, { recursive: true, force: true })
    }
})

test("NUL source paths throw outside the original Promise catch; native rejects without reproducing the crash", () => {
    const script = `const {ExifImage}=require(${JSON.stringify(require.resolve("exif"))}); const read=new Function("ExifImage","actionComplete", "return ("+${JSON.stringify(source.readExifData.toString())}+")")(ExifImage,()=>{}); read({id:"bad\\0path"});`
    const original = spawnSync(process.execPath, ["-e", script], { encoding: "utf8", timeout: 2000, maxBuffer: 65536 })
    assert.equal(original.status, 1, original.stderr)
    assert.match(original.stderr, /ERR_INVALID_ARG_VALUE/)
    assert.match(original.stderr, /Immediate/)
    assert.equal(native(["bad\0path"])[0].error.code, "exif_invalid")
})

test("static tag tables exactly match all source names and pinned dependency SHA", () => {
    const rust = fs.readFileSync(path.join(root, "crates/freeshow-exif/src/tags.rs"), "utf8")
    const sha = createHash("sha256")
        .update(fs.readFileSync(require.resolve("exif/lib/exif/ExifImage.js")))
        .digest("hex")
    assert.ok(rust.includes("source SHA256 " + sha))
    for (const [group, table] of Object.entries(ExifImage.TAGS)) {
        const part = rust.match(new RegExp("const " + group.toUpperCase() + "[^=]*= &\\[(.*?)\\];", "s"))[1]
        const names = [...part.matchAll(/\((\d+), ("(?:[^"\\]|\\.)*")\),/g)].map(([, id, name]) => [Number(id), JSON.parse(name)])
        assert.deepEqual(
            names,
            Object.entries(table)
                .map(([id, name]) => [Number(id), name])
                .sort(([a], [b]) => a - b)
        )
    }
})
